package main

// Bash 权限确认：策略 `ask` 在 desktop 上落到一张原生确认卡。
//
// 背景：desktop 原来用 agent.PermissionModeSkip，那个模式的 `ask` 分支是按「无人值守」设计的
// （channel / subagent / `tachi -p`——没有人在终端前），所以命中 ask 规则时直接拒绝，并回一句
// 「请让用户加 allow 规则」。可是 desktop 的用户就在窗口前面，GUI 也已经会渲染提问表单，于是
// 用户自己写进 config.yaml 的 ask 规则在唯一一个「看得见人」的前端上反而成了硬拒绝。
//
// 修法不是给 agent 层加第四个 PermissionMode：`PermissionModeExternal` 的语义本来就是「交给外部
// 主体决定」，ACP 就是这么接的（agent/acp/permission.go）。desktop 与它同构——一个带着真人的
// 外部主体——所以这里只实现一个 PermissionHandler，把决策通过事件送进窗口，等前端回填。
//
// 与 AskUserQuestion 是同一套「挂起—回答」范式（见 askuser.go）：handler 阻塞在 channel 上，
// binding 负责叫醒它。区别只有一个：AskUser 的答案走 agent 自己的 channel（RespondToAskUser），
// 而权限的决策完全属于前端，所以待确认表由 desktop 自己持有。

import (
	"context"
	"encoding/json"
	"fmt"

	"github.com/monsterxx03/tachi/agent"
	"github.com/monsterxx03/tachi/agent/tools"
)

// PermissionEvent is emitted to the frontend when a turn is parked on a user
// decision: a bash command that matched an `ask` rule, or an MCP search whose
// cache cost exceeds the configured budget. The answer goes back through
// AgentService.AnswerPermission.
//
// Preview is the agent's own rendering of what is being asked ($ command + the
// matched rule, see askPreview on the agent side) and is shown verbatim: a
// second parser of that format here would be free to drift from the one that
// writes it.
//
// Kind is the one thing the frontend does own: the STATIC chrome around the
// preview (title, the line under it, the button hints). It is not a license to
// re-explain the question — the reason is in Preview, and a card that paraphrased
// it would be the same drift the preview rule exists to prevent.
type PermissionEvent struct {
	SessionID string `json:"sessionId"`
	ToolID    string `json:"toolId"`
	ToolName  string `json:"toolName"`
	Kind      string `json:"kind"`
	Preview   string `json:"preview"`
}

// The kinds of ask that reach the confirm card. `kindBash` is the policy ask
// (agent_permission.go); `kindMCPSearch` is the MCP search cost card
// (agent/mcp_budget.go), whose preview is a cost estimate rather than a command —
// the two want different headlines, because the reader is being asked for
// different things (approve THIS command vs accept THIS spend). `kindFiles` is
// the file tools' ask (agent_permission_files.go): its preview names the tool and
// the path it would touch, so 「确认这条命令」 would send the reader looking for a
// command that is not there.
const (
	kindBash      = "bash"
	kindMCPSearch = "mcp_search"
	kindFiles     = "files"
)

// permEventKind maps a tool name to the card kind. The tool is the identity the
// agent already uses to decide which gate raised the ask, so the card cannot
// disagree with the gate about what is being asked.
func permEventKind(toolName string) string {
	switch toolName {
	case tools.ToolNameMCPSearchTools:
		return kindMCPSearch
	case tools.ToolNameRead, tools.ToolNameWrite, tools.ToolNameEdit:
		return kindFiles
	}
	return kindBash
}

// The decisions the confirm card can send. `allow_session` is the frontends'
// 「本会话全部允许」: it stops this session's ask rules from asking again, by flipping
// the switch the policy owns (AllowAllAsksForSession) — the same one the TUI's `a`
// flips. It is NOT a command memory: an agent's commands almost never repeat
// verbatim, so remembering one of them would be a button that cannot deliver.
// Deny rules are untouched — the agent decides them before an ask is raised.
const (
	permAllowOnce    = "allow_once"
	permAllowSession = "allow_session"
	permDeny         = "deny"
)

// noAskKey marks a run whose conversation has no turn on screen.
//
// A side-channel run (/review, /commit) reports into the panel's lane, not into the
// transcript, so there is nowhere to render a confirm card — parking it on a user
// decision would hang a run nobody can answer. The desktop marks its own one-off ctx
// (commands.go) instead of asking the agent layer to tell us: the lane is a desktop
// concept, and the marker must not leak into the other frontends' behaviour.
type noAskKey struct{}

func withoutAsk(ctx context.Context) context.Context { return context.WithValue(ctx, noAskKey{}, true) }

// askable reports whether this run has somewhere to ask the user.
func askable(ctx context.Context) bool {
	v, _ := ctx.Value(noAskKey{}).(bool)
	return !v
}

// permKey keyes a pending ask by session AND tool call. The tool call id alone is
// generated by the model, so two sessions can produce the same one; keying by the
// pair is what keeps an answer from reaching another conversation's ask.
func permKey(sessionID, toolID string) string { return sessionID + "\x00" + toolID }

// permissionHandler builds the PermissionHandler installed on one session's agent.
// `a` is captured for the session-wide approval: 「本会话全部允许」 flips the switch on
// that session's own policy (per agent, see agent_configure.go), which is also what
// makes the NEXT ask inside this session skip the handler entirely.
func (d *desktopApp) permissionHandler(sessionID string, a *agent.AIAgent) agent.PermissionHandler {
	return func(ctx context.Context, toolName, toolID, preview, args string) (bool, error) {
		return d.askPermission(ctx, sessionID, a, toolName, toolID, preview, args)
	}
}

// askPermission parks the agent goroutine until the user answers, then reports
// the decision as (approved, error).
//
// A cancelled context (Stop, or the app going away) releases the wait: the tool
// result then carries the cancellation, which is the same shape the TUI and ACP
// paths produce.
func (d *desktopApp) askPermission(ctx context.Context, sessionID string, a *agent.AIAgent, toolName, toolID, preview, args string) (bool, error) {
	// No turn on screen (a side-channel run): refuse with the explanation the agent's own
	// unattended branch gives, rather than parking a run that has no card to answer in.
	if !askable(ctx) {
		return false, fmt.Errorf("command requires interactive approval (matched an ask rule), "+
			"but a side-channel run has no conversation turn to confirm it in — the command was NOT "+
			"executed. Only the user can allow it, so say what was blocked and carry on without it "+
			"(preview: %s)", preview)
	}
	answer := make(chan string, 1)
	d.registerAsk(&pendingAsk{
		kind:      askKindPermission,
		sessionID: sessionID,
		toolID:    toolID,
		toolName:  toolName,
		preview:   preview,
		answer:    answer,
	})
	// Always drop the entry, whichever way the wait ends: a stale pending ask
	// would let a late click approve a command that is no longer running.
	defer d.dropAsk(sessionID, toolID)

	// The turn is parked on the user, so say so — the same status the parked
	// AskUserQuestion uses (setSessionState only reaches the UI when this IS the
	// displayed session, so a background ask cannot hijack the foreground). The marker on
	// this session's row comes from the ask registered above (see waitingSentence).
	d.setSessionState(sessionID, AgentState{Status: StatusBusy, Label: "授权", Detail: "等待确认"})
	if d.app != nil {
		d.app.Event.Emit("agent:permission", PermissionEvent{
			SessionID: sessionID,
			ToolID:    toolID,
			ToolName:  toolName,
			Kind:      permEventKind(toolName),
			Preview:   preview,
		})
	}
	d.notify.notifyPermission(sessionID, askSubjectOf(toolName, args))

	select {
	case decision := <-answer:
		switch decision {
		case permAllowSession:
			// 「本会话全部允许」: one setter flips both readers on this session's own agent —
			// the ask rules (evaluated inside the policy) and both judgment gates — so every
			// later ask skips this handler entirely (no card, no notification) instead of
			// parking again.
			a.AllowAllAsksForSession()
			// The search cost gate is not part of that policy (it answers a
			// different question — money, not rules) and reads only a bool from
			// this handler, so its own session switch has to be flipped here.
			if permEventKind(toolName) == kindMCPSearch {
				a.AllowMCPSearchForSession()
			}
		}
		return decision != permDeny, nil
	case <-ctx.Done():
		return false, ctx.Err()
	}
}

// AnswerPermission delivers the user's decision for a parked ask, unblocking the
// agent loop. sessionID + toolID must name the ask that is actually waiting: the
// frontend answers with the id it was given, so a card left over from an earlier
// call (or another conversation) is refused instead of approving something else.
func (s *AgentService) AnswerPermission(sessionID, toolID, decision string) string {
	if err := s.desk.answerPermission(sessionID, toolID, decision); err != nil {
		return err.Error()
	}
	return "ok"
}

// answerPermission is that answer path itself. Both the bound method above and the
// device link (badge.go) go through it: one decision has one implementation, so a
// click in the window and a button on the device cannot behave differently.
func (d *desktopApp) answerPermission(sessionID, toolID, decision string) error {
	if decision != permAllowOnce && decision != permAllowSession && decision != permDeny {
		return fmt.Errorf("unknown decision")
	}

	d.mu.Lock()
	ask := d.asks[permKey(sessionID, toolID)]
	d.mu.Unlock()
	// A row of the other kind is refused exactly like an absent one: the answer was
	// addressed to something that cannot take it.
	if ask == nil || ask.kind != askKindPermission {
		return fmt.Errorf("no such pending request")
	}

	select {
	case ask.answer <- decision:
		d.notifyAskAnswered(sessionID, toolID, askKindPermission)
		return nil
	default:
		// Buffered with capacity 1 and deleted by the waiting goroutine, so this
		// is unreachable unless the same ask is answered twice in the same
		// instant — refused rather than blocking the caller.
		return fmt.Errorf("already answered")
	}
}

// askSubjectOf is the one line a permission notification names: the command for a
// Bash ask, the target path for a file tool's ask, and "" for anything else (the
// notification then falls back to the bare waiting phrase).
//
// It parses the TOOL's own arguments — the same JSON the tool and the agent's
// policy check read, never a rendering of them — which is also why this is not a
// second parser of a preview: the preview is the agent's text and stays verbatim
// (see PermissionEvent), while this is one field out of the call itself.
func askSubjectOf(toolName, args string) string {
	switch toolName {
	case tools.ToolNameRead, tools.ToolNameWrite, tools.ToolNameEdit:
		var a struct {
			Path string `json:"path"`
		}
		if err := json.Unmarshal([]byte(args), &a); err != nil {
			return ""
		}
		return a.Path
	}
	return bashCommandOf(args)
}

// bashCommandOf extracts the "command" field of a Bash tool call's arguments — the
// one line a permission notification names (see notifyPermission). A parse failure
// is simply "no command", and the notification then falls back to the bare waiting
// phrase.
func bashCommandOf(args string) string {
	var a struct {
		Command string `json:"command"`
	}
	if err := json.Unmarshal([]byte(args), &a); err != nil {
		return ""
	}
	return a.Command
}

// GetSkipApproval reports whether the displayed session is in the 「无需审批」 mode: a bash command
// or a file call that matches an ask rule runs without a card. It is the session RECORD's own field
// (session.Session.SkipApproval), which is the durable half of the mode — the live half is the
// agent's session-wide approval, derived from the record every time an agent is built for it (see
// buildAgentForSession).
//
// It deliberately does NOT report a 「本会话全部允许」 answered on a card earlier in this process:
// that answer is about the questions this session has already raised, it lives on the agent and
// dies with the process. This control says what the session's MODE is, and the mode is what the
// record holds, so what it shows is what a restart will do.
func (s *AgentService) GetSkipApproval() bool {
	return s.desk.skipApprovalFor(s.desk.currentID())
}

// SetSkipApproval writes that mode onto the displayed session's record and applies it to the live
// agent. It answers "ok" or the reason it could not, and the frontend re-reads on a refusal rather
// than leaving a control claiming a mode that is not in force.
//
// The write itself lives in setSkipApprovalFor, addressed by session, because the phone switches
// this mode on the conversation it is looking at rather than on the one the window displays. There
// the record is written FIRST and applied second: a write that fails puts the record's copy back
// and touches no agent, so the two halves cannot end up describing different modes.
func (s *AgentService) SetSkipApproval(skip bool) string {
	d := s.desk
	if d.config() == nil {
		return "agent not ready"
	}
	id := d.currentID()
	if id == "" {
		return refuseNoSession
	}
	if err := d.setSkipApprovalFor(id, skip); err != nil {
		return err.Error()
	}
	return "ok"
}
