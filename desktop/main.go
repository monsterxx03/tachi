// Window background colours, mirroring --bg in base.css (light / dark). The
// window is opaque, so this is what shows for the instant before the frontend
// paints — it has to follow the theme, or a dark desktop gets a white flash on
// launch.
var (
	windowBgLight = application.NewRGB(0xf7, 0xf4, 0xee)
	windowBgDark  = application.NewRGB(0x25, 0x2a, 0x35)
)

// forcedAppearance reads TACHI_DESKTOP_APPEARANCE ("dark" / "light") and maps
// it to a Cocoa appearance, or returns DefaultAppearance to follow the system.
// Dev aid: it makes the dark theme inspectable without flipping the appearance
// of the whole machine.
func forcedAppearance() application.MacAppearanceType {
	switch strings.ToLower(os.Getenv("TACHI_DESKTOP_APPEARANCE")) {
	case "dark":
		return application.NSAppearanceNameDarkAqua
	case "light":
		return application.NSAppearanceNameAqua
	default:
		return application.DefaultAppearance
	}
}

// Assets embeds the built frontend. It is regenerated by `wails3 build` from
// `frontend/dist`; the embed pattern fails to compile until the frontend has
// been built once (same caveat as the tachi web console).
//
//go:embed all:frontend/dist
var assets embed.FS

func init() {
	// Register the custom event so the binding generator emits a strongly
	// typed JS/TS API for it. The payload is the agent state snapshot.
	application.RegisterEvent[AgentState]("agent:state")
	// Native file drops: the payload carries the dropped paths (see
	// desktop/fileservice.go).
	application.RegisterEvent[FileDropEvent]("agent:filedrop")
	// AskUserQuestion forms: the payload carries the questions to render (see
	// desktop/askuser.go).
	application.RegisterEvent[AskEvent]("agent:ask")
	// A parked ask that has been answered somewhere else — the device — so the window's
	// card can be taken down (see desktop/ask_answered.go). Emitting an unregistered
	// event is silently dropped, which would look exactly like "the card stays".
	application.RegisterEvent[AskAnsweredEvent]("agent:ask_answered")
	// Theme switches from the titlebar: the frontend sends the theme it just
	// applied (see desktop/uitheme.go).
	application.RegisterEvent[string](uiThemeEventName)
}

// localAssetRoute is the prefix the webview uses to reach files on disk (see
// assetHandler).
const localAssetRoute = "/local"

// assetHandler serves the embedded frontend assets, and additionally answers
// local files for the two cases the webview cannot load by path:
//
//	/local?p=<abs path>   — a single file, addressed by query
//	/local/<abs path>     — the same file with the disk path in the URL PATH
//
// The query form is what markdown images use (toLocalAsset). The path form
// exists for the HTML preview: the document loads from /local/.../report.html,
// so its own relative references ("./chart.js", "./style.css") resolve against
// that URL and land back here — under the query form the browser would resolve
// them against the app root and 404.
//
// Both forms serve any path the user can read, which is the desktop app's
// standing trade: the route is only reachable from its own webview, and the
// files being shown are the ones the agent just handed over.
func assetHandler(assets embed.FS) http.Handler {
	embedHandler := application.AssetFileServerFS(assets)
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if p := localAssetPath(r); p != "" {
			http.ServeFile(w, r, p)
			return
		}
		embedHandler.ServeHTTP(w, r)
	})
}

// localAssetPath maps a /local request onto a disk path, or returns "" when the
// request is not one (and should fall through to the embedded assets).
func localAssetPath(r *http.Request) string {
	if r.URL.Path == localAssetRoute {
		return r.URL.Query().Get("p")
	}
	rest, ok := strings.CutPrefix(r.URL.Path, localAssetRoute+"/")
	if !ok || rest == "" {
		return ""
	}
	// The URL path is already percent-decoded by net/http, and Clean keeps a
	// ".." segment from climbing out of the absolute path it is joined onto.
	return filepath.Clean("/" + rest)
}

func main() {
	desk := newDesktopApp()

	// Scripted-run hooks, installed before anything can use them (both self-gate on
	// their env var, so a normal launch is untouched): the MCP OAuth flow's browser is
	// replaced by a headless fetch when a smoke scenario asks for it, because a run
	// must never open a window on the machine it is running on.
	installDemoBrowserOpener()

	// The notification backend, registered below so Wails runs its startup — on Linux
	// that is what opens the D-Bus connection the notifier posts through, and an
	// unstarted backend panics on the first post (desktop/notify.go says why the
	// wrapper, and not the service itself, is what gets registered).
	notifyService := newNotificationService()

	app := application.New(application.Options{
		Name:        "Tachi",
		Description: "Tachi — AI Agent desktop companion",
		Services: []application.Service{
			application.NewService(&AgentService{desk: desk}),
			application.NewService(notifyService),
		},
		Assets: application.AssetOptions{
			Handler: assetHandler(assets),
		},
		// The one fact the frontend cannot work out for itself: which OS this process is
		// running on. Read synchronously there (Flags.GetFlag — `window._wails.flags`), which
		// is what lets a key handler decide ⌘ vs. Ctrl at module load with no round trip.
		// See frontend/src/platform.ts for why it comes from here instead of a UA sniff.
		Flags: map[string]any{"os": runtime.GOOS},
		Mac: application.MacOptions{
			// Keep the app alive in the menu bar when the window closes.
			ApplicationShouldTerminateAfterLastWindowClosed: false,
			// Regular in a real session; accessory while a script drives the app, so a run
			// never takes the foreground (see activationPolicy).
			ActivationPolicy: activationPolicy(),
		},
		Linux: application.LinuxOptions{
			// The Linux twin of ApplicationShouldTerminateAfterLastWindowClosed above:
			// closing the window only HIDES it (the close hook in main() turns the
			// delete into a hide), and the tray is the way back — so GTK must not quit
			// the app when the last window goes away.
			DisableQuitOnLastWindowClosed: true,
			// ProgramName fixes the window's TITLE, and only that. Nothing to do with the
			// app id: Wails derives WM_CLASS / the Wayland app_id (and therefore the id)
			// from the app Name — `org.wails.<sanitized name>` — so it comes out
			// `org.wails.tachi` either way, and g_set_prgname does not move it. The
			// .desktop file's StartupWMClass is what has to match that (desktop/build/
			// linux/tachi-desktop.desktop).
			//
			// The title needs it because the window is FRAMELESS here (window_frame_other.go):
			// a frameless window never reaches gtk_window_set_title — Wails' Linux setTitle
			// returns early on exactly that condition, on the assumption that a window with no
			// title bar has no title to show — so GTK falls back to g_get_prgname(), which is
			// the BINARY's name. The compositor is where that shows: Hyprland's window list,
			// its `title:` rules and the bar would all call this window "tachi-desktop".
			ProgramName: "Tachi",
		},
	})

	// Appearance: follow the system by default, unless the app has remembered a
	// manual choice from the titlebar switch (desktop_ui.json, mirrored by the
	// frontend) — or a forced value from TACHI_DESKTOP_APPEARANCE (dev aid),
	// which outranks both. Resolving this BEFORE the window exists is what keeps
	// a manual dark theme from flashing a light frame on launch.
	storedTheme := loadUIState().Theme
	forcedTheme := forcedAppearance()
	appearance, dark := resolveTheme(storedTheme, forcedTheme, app.Env.IsDarkMode())
	background := windowBgLight
	if dark {
		background = windowBgDark
	}

	// Menu bar: macOS gets Wails' default minus the WebKit zoom items, so ⌘= / ⌘- / ⌘0 reach
	// the page instead of magnifying the whole window; Linux gets none at all. The pair
	// (menu_darwin.go / menu_other.go) says why.
	installApplicationMenu(app)

	// Main conversational window.
	// Native macOS title bar is hidden but its traffic-light buttons remain
	// (like Zed): MacTitleBarHidden keeps the standard red/yellow/green controls
	// in the top-left while the content fills the window. InvisibleTitleBarHeight
	// gives the top region a drag handle. There is no Linux counterpart of either,
	// which is what Frameless answers there (see window_frame_*.go).
	window := app.Window.NewWithOptions(application.WebviewWindowOptions{
		Title:     "Tachi",
		Width:     1200,
		Height:    780,
		MinWidth:  900,
		MinHeight: 600,
		Frameless: framelessWindow,
		Mac: application.MacWindow{
			InvisibleTitleBarHeight: 44,
			// Opaque window: the UI is a flat, solid design (no vibrancy, no
			// backdrop blur anywhere), so the desktop behind the window must
			// not bleed through.
			Backdrop: application.MacBackdropNormal,
			TitleBar: application.MacTitleBarHidden,
			// The appearance resolved above: the user's remembered choice, the
			// dev override, or DefaultAppearance (= follow the system, which is
			// also what an untouched switch resolves to).
			Appearance: appearance,
		},
		// Matches --bg in base.css for the current theme, so the window never
		// flashes a different shade before the frontend paints. Kept in step by
		// themeController once the frontend is running.
		BackgroundColour: background,
		// Native drag-and-drop of files onto the window. Drops only register
		// on elements marked data-file-drop-target (the composer), and the
		// webview cannot read the paths itself — they arrive in Go via the
		// WindowFilesDropped event below and are forwarded to the frontend.
		EnableFileDrop: true,
		// A run that must not take the foreground is created HIDDEN and put on screen by
		// the demo bootstrap instead, at the BOTTOM of the window stack
		// (orderWindow:NSWindowBelow — never makeKeyAndOrderFront, which activates the app
		// and takes the user's focus): see webview_awake_darwin.go.
		Hidden: demoNoActivate(),
		URL:    "/",
	})
	desk.app = app
	desk.window = window

	// ⌘W and the red button HIDE the main window; only 退出 Tachi Desktop closes the app.
	//
	// The reason is not taste. On darwin a user-initiated close ALWAYS destroyed this window:
	// AppKit's `windowShouldClose` returns NO, the framework emits a closing event instead, and its
	// own unconditionally-registered listener then ran `impl.close` + `Window.Remove(id)`. Every
	// handle to the window — `desk.window`, the notifier's, the theme controller's — pointed at
	// nothing afterwards, and all three ways back to it went silent at once: the tray's
	// 「打开主窗口」 (Show on a destroyed window is a no-op: `Run` only creates an
	// impl that is not nil), a notification click (same call), and a Dock click — Wails' own
	// `applicationShouldHandleReopen` handler only shows windows that still EXIST and are
	// invisible, so with the window gone there was nothing to show.
	//
	// Hooks run SYNCHRONOUSLY before the listeners and `WindowEvent.Cancel` stops the remaining
	// ones, which makes this the one place the close can be turned into a hide. Hiding is also what
	// makes all three paths work again WITHOUT touching them: the window stays in the manager, so
	// the tray finds it, the notifier finds it, and a Dock click finds it as "exists, not visible"
	// — which is exactly the case Wails' reopen handler is written for. And the page is never torn
	// down: the transcript on screen, a drafted message and a streaming turn all survive.
	//
	// The shutdown path must go through, or the app cannot exit: `app.Quit` → `[NSApp terminate:]`
	// → cleanup() closes every window, and quitting is already true by then because cleanup runs
	// its shutdown tasks BEFORE that loop.
	window.RegisterHook(events.Common.WindowClosing, func(e *application.WindowEvent) {
		if desk.quitting.Load() {
			return
		}
		window.Hide()
		e.Cancel()
	})
	app.OnShutdown(func() {
		desk.quitting.Store(true)
		// The device link is stopped explicitly: its reconnect loop owns a goroutine that
		// would otherwise keep waking up while the process is going away.
		desk.stopBadge()
		// And the bar's copy of the readout is withdrawn: a consumer that keeps drawing it
		// would be reporting a process that no longer exists (see barstatus.go).
		removeDesktopStatus()
	})

	// Native notifications for the two moments the app waits on the user (a
	// finished turn, a parked AskUserQuestion). They are posted only while the
	// window is unfocused; permission is asked once, in the background, so the
	// prompt is not tied to the first notification. See desktop/notify.go.
	desk.notify = newNotifier(notifyService, window)
	desk.notify.onNotificationClick()
	go desk.notify.requestAuthorization()

	// Forward native file drops to the frontend, which inserts @-references
	// into the input area. The element id lets the frontend decide where the
	// drop landed (and ignore drops outside the drop targets).
	window.OnWindowEvent(events.Common.WindowFilesDropped, func(e *application.WindowEvent) {
		elementID := ""
		if dt := e.Context().DropTargetDetails(); dt != nil {
			elementID = dt.ElementID
		}
		desk.emitFileDrop(e.Context().DroppedFiles(), elementID)
	})

	// Keep the window background in step with the theme while the app runs:
	// the frontend mirrors every switch over uiThemeEventName (it owns the
	// choice — its inline boot script is what paints the first frame), and the
	// system-appearance listener covers the pre-paint colour and the frame
	// around the webview. Both are no-ops while a manual choice or the dev
	// override owns the theme (see themeController).
	themes := newThemeController(window, storedTheme, forcedTheme)
	app.Event.On(uiThemeEventName, func(e *application.CustomEvent) {
		if theme, ok := e.Data.(string); ok {
			themes.setFromFrontend(theme)
		}
	})
	app.Event.OnApplicationEvent(events.Common.ThemeChanged, func(*application.ApplicationEvent) {
		themes.onSystemChange(app.Env.IsDarkMode())
	})

	// Menu bar item reflecting the agent state.
	desk.tray = setupTray(desk)

	// Initial state broadcast (drives tray label/icon + frontend status bar).
	desk.setSessionState("", AgentState{Status: StatusIdle, Label: "空闲", Detail: "就绪"})

	// Boot the real tachi agent (falls back to simulated turns on failure).
	if err := desk.initAgent(context.Background()); err != nil {
		log.Printf("agent unavailable, falling back to simulated turns: %v", err)
		desk.setSessionState("", AgentState{Status: StatusIdle, Label: "空闲", Detail: "未配置 agent（模拟模式）"})
	}

	// The device link (badge.go): a screen the agent's questions can reach when nobody is
	// looking at the window. It is off unless config or TACHI_BADGE names a transport.
	// After initAgent, because the config it reads belongs to the app that just booted.
	desk.startBadge(desk.config())

	// Optional self-test driver (TACHI_DEMO): inject JS to type & send from
	// within the webview, so we can exercise input + state transitions without
	// relying on system-level mouse/keyboard coordinates.
	//
	// It starts from ApplicationStarted (Wails' Cross-platform name for "the app is up and its
	// runtime exists" — ApplicationDidFinishLaunching on macOS, ApplicationStartup on Linux),
	// NOT from a goroutine that sleeps: the bootstrap's first act is a dispatch onto the main
	// thread, and dispatching before App.Run() has built the runtime dereferences a nil platform
	// impl inside Wails and PANICS the whole process (measured: the app appeared to "not start" —
	// no window, no driver, no log — while a busy machine was simply slower than the sleep we
	// used to guess with). This event is that moment, so there is nothing left to guess.
	if demoEnabled() {
		app.Event.OnApplicationEvent(events.Common.ApplicationStarted,
			func(*application.ApplicationEvent) { go runJsDemo(window) })
	}

	// Run the application.
	if err := app.Run(); err != nil {
		log.Fatal(err)
	}
	desk.teardownAgent()
}
